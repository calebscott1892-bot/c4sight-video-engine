import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..');
const manifestPath = join(repoRoot, 'src/design-system/c4sightAssetManifest.ts');
const outputPath = join(
  repoRoot,
  'src/design-system/c4sightAssetAvailability.generated.ts',
);

const manifestSource = readFileSync(manifestPath, 'utf8');
const filePaths = Array.from(
  new Set(
    [...manifestSource.matchAll(/filePath:\s*'([^']+)'/g)].map(
      (match) => match[1],
    ),
  ),
).sort();

const availability = Object.fromEntries(
  filePaths.map((filePath) => [
    filePath,
    existsSync(join(repoRoot, 'public', filePath.replace(/^\//, ''))),
  ]),
);

const output = `// Generated by scripts/update-c4sight-asset-readiness.mjs.
// Run npm run assets:scan after adding or removing files in public/c4sight/assets.

export const c4sightAssetAvailability = ${JSON.stringify(
  availability,
  null,
  2,
)} as const;
`;

writeFileSync(outputPath, output);
console.log(
  `Scanned ${filePaths.length} C4Sight asset paths. Ready: ${
    Object.values(availability).filter(Boolean).length
  }/${filePaths.length}`,
);
